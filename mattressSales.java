    public class ProcessButtonFrame extends JFrame {

    private JTextField inputField;
    private JButton processButton;
    private JLabel resultLabel;

    public ProcessButtonFrame() {
        initComponents();
    }

    // Initialize GUI components
    private void initComponents() {
        // Create components
        inputField = new JTextField(15);
        processButton = new JButton("Process");
        resultLabel = new JLabel("Result will appear here");

        // Add ActionListener to the button
        processButton.addActionListener(new ActionListener() {
            @Override
            public void actionPerformed(ActionEvent e) {
                processInput();
            }
        });

        // Layout setup
        JPanel panel = new JPanel();
        panel.add(new JLabel("Enter text:"));
        panel.add(inputField);
        panel.add(processButton);
        panel.add(resultLabel);

        // Frame settings
        this.setTitle("Process Button Example");
        this.setDefaultCloseOperation(JFrame.EXIT_ON_CLOSE);
        this.setContentPane(panel);
        this.pack();
        this.setLocationRelativeTo(null); // Center on screen
    }

    // Method to handle button click
    private void processInput() {
        String input = inputField.getText().trim();

        if (input.isEmpty()) {
            resultLabel.setText("Please enter something!");
            return;
        }

        // Example processing: convert to uppercase
        String processed = input.toUpperCase();
        resultLabel.setText("Processed: " + processed);
    }

    // Main method to run the GUI
    public static void main(String[] args) {
        SwingUtilities.invokeLater(() -> {
            new ProcessButtonFrame().setVisible(true);
        });
    }
}

private void processButtonActionPerformed(java.awt.event.ActionEvent evt) {
    // Your processing code here
    String input = inputField.getText().trim();
    if (input.isEmpty()) {
        resultLabel.setText("Please enter something!");
        return;
    }
    resultLabel.setText("Processed: " + input.toUpperCase());
}
